// Builds the astronaut HUD's 3D Mars scene bundle (integration mode only; myomars-hud/README.md,
// docs/myomars/HUD-INTEGRATION-MODE.md):
//
//   myomars-hud/scene/mars-scene.src.js  (ES module, imports from "three")
//     → myomars-hud/scene/mars-scene.js  (COMMITTED, generated: tree-shaken, minified IIFE → window.MyoMarsScene)
//
// The HUD is plain static HTML with no build step at run time, so the bundle is committed. Rebuild after editing
// the source:   npm run hud:scene        Check that the committed bundle is current:   node scripts/build-hud-scene.mjs --check
//
// three.js (MIT, LICENSES/MIT-three.js.txt) is bundled from node_modules/three/src (three@0.186.1, pinned in
// package.json) as a SHADERMATERIAL-ONLY build: the scene draws only ShaderMaterial meshes with its own GLSL, so the
// renderer code paths for built-in materials, PMREM environment maps and WebXR are never taken. Those modules are
// replaced by small stubs below (about 190 KB less). The guard below fails the build if the scene source starts to
// import something that would need them; if it ever does, drop the stub instead of working around it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { rolldown } from "rolldown";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "myomars-hud/scene/mars-scene.src.js");
const OUT = join(ROOT, "myomars-hud/scene/mars-scene.js");
const THREE_SRC = join(ROOT, "node_modules/three/src/");
const THREE_VERSION = JSON.parse(readFileSync(join(ROOT, "node_modules/three/package.json"), "utf8")).version;
const check = process.argv.includes("--check");

// ---- guard: the scene may only use what this ShaderMaterial-only build supports
const source = readFileSync(SRC, "utf8");
const imported = [...source.matchAll(/import\s*\{([^}]*)\}\s*from\s*['"]three['"]/g)]
  .flatMap((m) => m[1].split(",").map((s) => s.trim().split(/\s+as\s+/)[0]))
  .filter(Boolean);
const NEEDS_FULL_BUILD = /^(?!ShaderMaterial$|RawShaderMaterial$).*Material$|^(PMREMGenerator|ShaderLib|ShaderChunk|UniformsLib|WebGLCubeRenderTarget|Sprite|Points|Line|LineSegments|LineLoop|CubeTexture|CubeTextureLoader)$/;
const bad = imported.filter((n) => NEEDS_FULL_BUILD.test(n));
if (bad.length) {
  console.error(`build-hud-scene: the scene imports ${bad.join(", ")}, which this ShaderMaterial-only three.js build leaves out.`);
  process.exit(1);
}
if (/scene\.(background|environment)\s*=|\.envMap\b|renderer\.xr\b|shadowMap\.enabled\s*=\s*true/.test(source)) {
  console.error("build-hud-scene: texture backgrounds, environment maps, WebXR and shadow maps are not in this build.");
  process.exit(1);
}

// ---- stubs for the three.js modules the scene never reaches
const STUBS = {
  // Built-in material shaders: the scene's ShaderMaterials only need the two chunks WebGLProgram always inserts.
  "renderers/shaders/ShaderChunk.js": [
    "import colorspace_pars_fragment from './ShaderChunk/colorspace_pars_fragment.glsl.js';",
    "import tonemapping_pars_fragment from './ShaderChunk/tonemapping_pars_fragment.glsl.js';",
    "export const ShaderChunk = { colorspace_pars_fragment, tonemapping_pars_fragment };",
  ].join("\n"),
  "renderers/shaders/ShaderLib.js": "export const ShaderLib = {};",
  // Environment-map prefiltering (MeshStandardMaterial envMap / scene.environment only).
  "extras/PMREMGenerator.js": "export class PMREMGenerator { constructor() { throw new Error('PMREMGenerator is not in the HUD scene build'); } }",
  // WebXR: never enabled; WebGLRenderer only reads these members while xr.enabled is false.
  "renderers/webxr/WebXRManager.js": [
    "import { EventDispatcher } from '../../core/EventDispatcher.js';",
    "export class WebXRManager extends EventDispatcher {",
    "  constructor() { super(); this.enabled = false; this.isPresenting = false; this.cameraAutoUpdate = true; }",
    "  getEnvironmentBlendMode() { return 'opaque'; }",
    "  hasDepthSensing() { return false; }",
    "  getDepthSensingMesh() { return null; }",
    "  setAnimationLoop() {}",
    "  updateCamera() {}",
    "  getCamera() { return null; }",
    "  dispose() {}",
    "}",
  ].join("\n"),
};
const used = new Set();
const threeLite = {
  name: "three-shadermaterial-only",
  load(id) {
    if (!id.startsWith(THREE_SRC)) return null;
    const rel = id.slice(THREE_SRC.length).replace(/\\/g, "/");
    if (!(rel in STUBS)) return null;
    used.add(rel);
    return STUBS[rel];
  },
};

const banner =
  `/* MyoMars HUD · illustrative 3D Mars scene. GENERATED by scripts/build-hud-scene.mjs from scene/mars-scene.src.js: do not edit. ` +
  `Includes three.js ${THREE_VERSION} (ShaderMaterial-only build), MIT License, Copyright © 2010-2026 three.js authors: LICENSES/MIT-three.js.txt. */\n`;

const bundle = await rolldown({
  input: SRC,
  resolve: { alias: { three: join(THREE_SRC, "Three.js") } },
  plugins: [threeLite],
  logLevel: "warn",
});
const { output } = await bundle.generate({ format: "iife", name: "MyoMarsScene", minify: true });
await bundle.close();
const code = banner + output[0].code;
const missing = Object.keys(STUBS).filter((k) => !used.has(k));
if (missing.length) {
  console.error(`build-hud-scene: stub(s) not applied (three.js layout changed?): ${missing.join(", ")}`);
  process.exit(1);
}

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
if (check) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    /* missing */
  }
  if (current !== code) {
    console.error("myomars-hud/scene/mars-scene.js is out of date: run npm run hud:scene");
    process.exit(1);
  }
  console.log(`myomars-hud/scene/mars-scene.js is up to date (${kb(code.length)})`);
} else {
  writeFileSync(OUT, code);
  console.log(`myomars-hud/scene/mars-scene.js: ${kb(Buffer.byteLength(code))} minified, ${kb(gzipSync(code).length)} gzip · three ${THREE_VERSION} (ShaderMaterial-only)`);
}
